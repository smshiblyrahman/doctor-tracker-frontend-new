// Generates app/tailwind-safelist.css: every class-like token used in the source,
// fed to Tailwind with `@source inline(...)`.
//
// Why: Tailwind v4 finds class names with a native Rust scanner. Where that binary
// cannot load (e.g. Windows with an Application Control policy that blocks unsigned
// .node files) it falls back to a WASI build that cannot read the project files,
// and no utilities are generated. Inline sources bypass file scanning entirely.
// On machines where the native scanner works this file is redundant but harmless.
// Runs automatically before `dev` and `build`.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const DIRS = ["app", "components", "hooks", "lib", "stores"];
const OUT = path.join(root, "app", "tailwind-safelist.css");

function* walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(tsx|ts|jsx|js|mjs)$/.test(entry.name)) yield full;
  }
}

/** An unbalanced "(" or "[" makes Tailwind's inline() parser drop every later token. */
function balanced(value) {
  let paren = 0;
  let bracket = 0;
  for (const ch of value) {
    if (ch === "(") paren += 1;
    else if (ch === ")") paren -= 1;
    else if (ch === "[") bracket += 1;
    else if (ch === "]") bracket -= 1;
    if (paren < 0 || bracket < 0) return false;
  }
  return paren === 0 && bracket === 0;
}

const tokens = new Set();
// Content of string and template literals.
const literal = /"([^"\\\n]*)"|'([^'\\\n]*)'|`([^`\\]*)`/g;
// Plausible utility tokens: letters/digits plus Tailwind's variant/arbitrary syntax.
const token = /^[!-]?[a-z@*[][\w\-:/.[\]()%#&>~=,+*@!]*$/i;

for (const dir of DIRS) {
  for (const file of walk(path.join(root, dir))) {
    const source = fs.readFileSync(file, "utf8");
    for (const match of source.matchAll(literal)) {
      const text = match[1] ?? match[2] ?? match[3] ?? "";
      for (const part of text.split(/\s+/)) {
        if (part.length > 1 && part.length < 120 && token.test(part) && balanced(part) && !part.endsWith(",") && !part.includes("${")) tokens.add(part);
      }
    }
  }
}

const sorted = [...tokens].sort();
const css = `/* Generated by scripts/tailwind-safelist.mjs: do not edit. See the script for why it exists. */
@source inline("${sorted.join(" ")}");
`;
fs.writeFileSync(OUT, css);
console.log(`[tailwind-safelist] ${sorted.length} tokens -> ${path.relative(root, OUT)}`);
